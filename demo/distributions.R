library(statinfer)

cat("Normal Distribution N(0, 1)\n")
norm_dist <- NormalDistribution$new(0, 1)
cat(sprintf("   pdf(0)     = %.6f\n", norm_dist$pdf(0)))
cat(sprintf("   pdf(1)     = %.6f\n", norm_dist$pdf(1)))
cat(sprintf("   cdf(1.96)  = %.6f\n", norm_dist$cdf(1.96)))
cat(sprintf("   mean()     = %.6f\n", norm_dist$mean()))
cat(sprintf("   variance() = %.6f\n", norm_dist$variance()))
cat("   10 samples:", paste(round(norm_dist$sample(10), 3), collapse = ", "), "\n\n")

cat("Binomial Distribution B(10, 0.5)\n")
binom_dist <- BinomialDistribution$new(10, 0.5)
cat(sprintf("   pmf(5)     = %.6f\n", binom_dist$pmf(5)))
cat(sprintf("   cdf(5)     = %.6f\n", binom_dist$cdf(5)))
cat(sprintf("   mean()     = %.6f\n", binom_dist$mean()))
cat(sprintf("   variance() = %.6f\n", binom_dist$variance()))
cat("   10 samples:", paste(binom_dist$sample(10), collapse = ", "), "\n\n")

cat("Poisson Distribution Pois(3)\n")
